# --------------------------------------------------------------------------- helpers


def _load_payload(path: str) -> Any:
    text = sys.stdin.read() if path == "-" else Path(path).read_text(encoding="utf-8")
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise HookInputError(f"{path}: not valid JSON: {exc}") from exc


def _event_from_payload(payload: Any, *, warnings: list[str]) -> Event:
    try:
        return parse_event(payload)
    except HookInputError as strict_error:
        event = parse_event(payload, strict=False)
        warnings.append(f"payload does not match the documented schema: {strict_error}")
        return event


def _collection(args: argparse.Namespace, event: Event | None) -> Collection:
    cwd: Path | None = None
    walk_up = True
    if getattr(args, "cwd", None):
        cwd = Path(args.cwd)
        walk_up = False
    elif event is not None and isinstance(event.cwd, str) and Path(event.cwd).is_dir():
        cwd = Path(event.cwd)
    home = Path(args.home) if getattr(args, "home", None) else None
    env = dict(os.environ)
    if getattr(args, "plugins_root", None):
        env["CLAUDE_CODE_PLUGIN_CACHE_DIR"] = args.plugins_root
    if home is not None:
        env.pop("CLAUDE_CONFIG_DIR", None)
    settings_files = [Path(p) for p in args.settings] if getattr(args, "settings", None) else None
    return collect(
        cwd,
        home=home,
        env=env,
        settings_files=settings_files,
        plugins=not getattr(args, "no_plugins", False),
        walk_up=walk_up,
    )


def _short(text: str | None, width: int = 60) -> str:
    if not text:
        return ""
    text = " ".join(text.split())
    return text if len(text) <= width else text[: width - 3] + "..."


def _display_path(path: Path) -> str:
    home = str(Path.home())
    text = str(path)
    return "~" + text[len(home) :] if text.startswith(home) else text


