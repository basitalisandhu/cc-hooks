def _record_handler(record_file: Path) -> dict[str, Any]:
    executable = shutil.which("cc-hooks") or "cc-hooks"
    return {
        "type": "command",
        "command": executable,
        "args": ["record", "--append", str(record_file)],
        "timeout": 5,
        "statusMessage": "cc-hooks: recording hook payload",
    }


def _is_record_handler(entry: Any) -> bool:
    if not isinstance(entry, dict):
        return False
    args = entry.get("args")
    command = str(entry.get("command", ""))
    return (
        isinstance(args, list)
        and len(args) >= 2
        and args[0] == "record"
        and args[1] == "--append"
        and os.path.basename(command) in ("cc-hooks", "cc-hooks.exe")
    )


def _settings_target(args: argparse.Namespace) -> Path:
    if args.file:
        return Path(args.file)
    from .settings import config_dir, project_root

    if args.scope == "user":
        return config_dir(Path(args.home) if args.home else None) / "settings.json"
    root = project_root(Path(args.cwd) if args.cwd else Path.cwd())
    name = "settings.json" if args.scope == "project" else "settings.local.json"
    return root / ".claude" / name


def cmd_record(args: argparse.Namespace) -> int:
    if args.append is not None:
        return _record_append(args.append)
    if args.to:
        return _record_to(args)
    target = _settings_target(args)
    data: dict[str, Any] = {}
    if target.is_file():
        try:
            data = json.loads(target.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            print(f"cc-hooks record: {target}: invalid JSON: {exc}", file=sys.stderr)
            return 2
        if not isinstance(data, dict):
            print(f"cc-hooks record: {target}: top level must be an object", file=sys.stderr)
            return 2
    hooks = data.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        print(f"cc-hooks record: {target}: 'hooks' must be an object", file=sys.stderr)
        return 2
    events = [e.strip() for e in args.events.split(",") if e.strip()]
    unknown = [e for e in events if e not in EVENTS]
    if unknown:
        print(f"cc-hooks record: unknown event(s): {', '.join(unknown)}", file=sys.stderr)
        return 2
    if args.uninstall:
        removed = 0
        for event in list(hooks):
            groups = hooks.get(event)
            if not isinstance(groups, list):
                continue
            kept_groups = []
            for group in groups:
                if isinstance(group, dict) and isinstance(group.get("hooks"), list):
                    before = len(group["hooks"])
                    group["hooks"] = [h for h in group["hooks"] if not _is_record_handler(h)]
                    removed += before - len(group["hooks"])
                    if not group["hooks"]:
                        continue
                kept_groups.append(group)
            if kept_groups:
                hooks[event] = kept_groups
            else:
                del hooks[event]
        if not hooks:
            del data["hooks"]
        target.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        print(f"removed {removed} record handler(s) from {_display_path(target)}")
        return 0
    record_file = (
        Path(args.record_file).expanduser()
        if args.record_file
        else DEFAULT_RECORD_FILE.expanduser()
    )
    handler = _record_handler(record_file)
    added = 0
    for event in events:
        groups = hooks.setdefault(event, [])
        if not isinstance(groups, list):
            print(f"cc-hooks record: {target}: hooks.{event} must be a list", file=sys.stderr)
            return 2
        present = any(
            isinstance(g, dict)
            and any(_is_record_handler(h) for h in g.get("hooks", []) if isinstance(h, dict))
            for g in groups
        )
        if present:
            continue
        groups.append({"hooks": [handler]})
        added += 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(
        f"installed record handler on {', '.join(events)} in {_display_path(target)} "
        f"({added} added)"
    )
    print(f"payloads will be appended to {_display_path(record_file)}")
    print("convert them with: cc-hooks record --to fixtures/")
    return 0


def _record_append(path_text: str) -> int:
    """The installed hook: append the raw payload and never fail the tool call."""
    try:
        path = Path(path_text).expanduser() if path_text else DEFAULT_RECORD_FILE.expanduser()
        text = sys.stdin.read()
        now = dt.datetime.now(dt.UTC).isoformat(timespec="seconds")
        try:
            entry: dict[str, Any] = {"recorded_at": now, "event": json.loads(text)}
        except json.JSONDecodeError:
            entry = {"recorded_at": now, "raw": text}
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")
    except Exception as exc:
        print(f"cc-hooks record: {exc}", file=sys.stderr)
    return 0


def _record_to(args: argparse.Namespace) -> int:
    source = (
        Path(args.from_file).expanduser() if args.from_file else DEFAULT_RECORD_FILE.expanduser()
    )
    if not source.is_file():
        print(f"cc-hooks record: nothing recorded at {_display_path(source)}", file=sys.stderr)
        return 1
    out_dir = Path(args.to)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = 0
    skipped = 0
    existing = len(list(out_dir.glob("*.json")))
    for line in source.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            skipped += 1
            continue
        payload = entry.get("event") if isinstance(entry, dict) else None
        if not isinstance(payload, dict) or not isinstance(payload.get("hook_event_name"), str):
            skipped += 1
            continue
        name = payload["hook_event_name"]
        tool = payload.get("tool_name")
        suffix = f"-{tool}" if isinstance(tool, str) else ""
        safe = "".join(c if c.isalnum() or c in "-_" else "_" for c in f"{name}{suffix}")
        index = existing + written + 1
        target = out_dir / f"{index:03d}-{safe}.json"
        fixture = {
            "event": payload,
            "expect": {"decision": "none"},
            "recorded_at": entry.get("recorded_at"),
            "note": "Edit expect.decision to what your hooks should return for this payload.",
        }
        target.write_text(json.dumps(fixture, indent=2) + "\n", encoding="utf-8")
        written += 1
    print(f"wrote {written} fixture(s) to {out_dir}" + (f", skipped {skipped}" if skipped else ""))
    return 0


# --------------------------------------------------------------------------- parser


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="cc-hooks",
        description=(
            "Explain, test and record Claude Code hooks without running anything destructive."
        ),
    )
    parser.add_argument("--version", action="version", version=f"cc-hooks {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    p_events = sub.add_parser("events", help="list the documented hook events")
    p_events.add_argument(
        "--json", action="store_true", help="print the full event registry as JSON"
    )
    p_events.add_argument("--markdown", action="store_true", help="print docs/events.md")
    p_events.set_defaults(func=cmd_events)

    def add_settings_options(p: argparse.ArgumentParser) -> None:
        p.add_argument(
            "--cwd",
            help=(
                "the directory the session started in, used as-is (default: the nearest "
                ".claude/ or .git above the event's cwd, else above the current directory)"
            ),
        )
        p.add_argument("--home", help="home directory holding .claude/ (default: your home)")
        p.add_argument(
            "--settings",
            action="append",
            metavar="FILE",
            help="use only this settings file (repeatable); skips user, managed and plugin hooks",
        )
        p.add_argument("--plugins-root", help="plugins directory (default: <config dir>/plugins)")
        p.add_argument("--no-plugins", action="store_true", help="ignore plugin hooks")

    p_explain = sub.add_parser("explain", help="which handlers would run for an event payload")
    p_explain.add_argument("event", help="path to a hook payload JSON file, or - for stdin")
    add_settings_options(p_explain)
    p_explain.add_argument("--json", action="store_true", help="machine-readable output")
    p_explain.set_defaults(func=cmd_explain)

    p_test = sub.add_parser("test", help="replay fixtures through matching command hooks")
    p_test.add_argument("paths", nargs="+", help="fixture files or directories of *.json")
    add_settings_options(p_test)
    p_test.add_argument(
        "--exec",
        action="store_true",
        help="run hooks without CC_HOOKS_DRY_RUN=1 (real side effects)",
    )
    p_test.add_argument("--no-run", action="store_true", help="only print what would execute")
    p_test.add_argument("--timeout", type=float, default=30.0, help="cap per hook, seconds (30)")
    p_test.add_argument("--report", metavar="FILE", help="write results as JSON")
    p_test.add_argument("-v", "--verbose", action="store_true", help="show notes and stderr")
    p_test.set_defaults(func=cmd_test)

    p_record = sub.add_parser("record", help="capture real payloads as fixtures")
    group = p_record.add_mutually_exclusive_group(required=True)
    group.add_argument("--install", action="store_true", help="add the recording handlers")
    group.add_argument("--uninstall", action="store_true", help="remove the recording handlers")
    group.add_argument(
        "--append", nargs="?", const="", metavar="FILE", help="(the hook) append stdin"
    )
    group.add_argument("--to", metavar="DIR", help="convert recorded payloads into fixtures")
    p_record.add_argument("--scope", choices=("user", "project", "local"), default="local")
    p_record.add_argument("--file", help="settings file to edit (overrides --scope)")
    p_record.add_argument("--events", default=",".join(RECORD_EVENTS), help="events to record")
    p_record.add_argument("--record-file", help=f"where payloads go ({DEFAULT_RECORD_FILE})")
    p_record.add_argument("--from", dest="from_file", help="recorded file to convert")
    p_record.add_argument("--cwd")
    p_record.add_argument("--home")
    p_record.set_defaults(func=cmd_record)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
